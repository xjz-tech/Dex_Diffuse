      EPISODE_LOG="${RUN_OUTPUT}/episodes.jsonl" INITIAL_STATE_DUMP="${RUN_OUTPUT}/initial_state.npz" \
      bash "${OUT}/source/eval/xjz_test.sh" > "${RUN_OUTPUT}/run.log" 2>&1
    touch "${RUN_OUTPUT}/RUN_COMPLETE"
done
